CREATE TABLE CUST (
    CUST_ID BIGINT NOT NULL,
    CUST_NAME TEXT,
    COUNTRY_CODE TEXT NOT NULL,
    CONSTRAINT PK_CUST_PK PRIMARY KEY (CUST_ID),
    CONSTRAINT FK_CUST_ORDER_FK FOREIGN KEY (CUST_ID) REFERENCES ORDER(CUST_ID),
    CONSTRAINT FK_CUST_COUNTRY_FK FOREIGN KEY (COUNTRY_CODE) REFERENCES COUNTRY(COUNTRY_CODE)
);
COMMENT ON TABLE CUST IS 'Customer master data';
CREATE INDEX IX_CUST_ORDER_IDX ON CUST(CUST_ID);
CREATE INDEX IX_CUST_COUNTRY_IDX ON CUST(COUNTRY_CODE);
