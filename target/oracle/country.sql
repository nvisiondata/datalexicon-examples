CREATE TABLE CTRY (
    CTRY_CD VARCHAR2(255) NOT NULL,
    CTRY_NAME VARCHAR2(255) NOT NULL,
    CONSTRAINT PK_CTRY PRIMARY KEY (CTRY_CD),
    CONSTRAINT FK_CTRY_CUST FOREIGN KEY (CTRY_CD) REFERENCES CUST(CTRY_CD),
    CONSTRAINT FK_CTRY_SALES_ORD FOREIGN KEY (CTRY_CD) REFERENCES SALES_ORD(SHIPPING_CTRY_CD)
);
COMMENT ON TABLE CTRY IS 'Country lookup table';
CREATE INDEX IDX_CTRY_CUST ON CTRY(CTRY_CD);
CREATE INDEX IDX_CTRY_SALES_ORD ON CTRY(CTRY_CD);
