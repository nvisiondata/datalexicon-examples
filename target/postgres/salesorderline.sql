CREATE TABLE SALES_ORD_LINE (
    SALES_ORD_LINE_ID BIGINT NOT NULL,
    SALES_ORD_ID BIGINT NOT NULL,
    PROD_ID BIGINT NOT NULL,
    LINE_NBR INTEGER NOT NULL,
    QTY INTEGER NOT NULL,
    UNIT_PRC TEXT NOT NULL,
    CONSTRAINT PK_SALES_ORD_LINE PRIMARY KEY (SALES_ORD_LINE_ID),
    CONSTRAINT FK_SALES_ORD_LINE_SALES_ORD FOREIGN KEY (SALES_ORD_ID) REFERENCES SALES_ORD(SALES_ORD_ID),
    CONSTRAINT FK_SALES_ORD_LINE_PROD FOREIGN KEY (PROD_ID) REFERENCES PROD(PROD_ID)
);
COMMENT ON TABLE SALES_ORD_LINE IS 'Product and purchase details captured on a sales order';
COMMENT ON COLUMN SALES_ORD_LINE.SALES_ORD_LINE_ID IS 'unique identifier for a sales order line';
CREATE INDEX IDX_SALES_ORD_LINE_SALES_ORD ON SALES_ORD_LINE(SALES_ORD_ID);
CREATE INDEX IDX_SALES_ORD_LINE_PROD ON SALES_ORD_LINE(PROD_ID);
