CREATE TABLE ORDER (
    ORDER_ID BIGINT NOT NULL,
    ORDER_DATE TIMESTAMP NOT NULL,
    CUST_ID BIGINT NOT NULL,
    COUNTRY_CODE TEXT NOT NULL,
    CONSTRAINT PK_ORDER_PK PRIMARY KEY (ORDER_ID, CUST_ID),
    CONSTRAINT FK_ORDER_CUST_FK FOREIGN KEY (CUST_ID) REFERENCES CUST(CUST_ID),
    CONSTRAINT FK_ORDER_COUNTRY_FK FOREIGN KEY (COUNTRY_CODE) REFERENCES COUNTRY(COUNTRY_CODE)
);
COMMENT ON TABLE ORDER IS 'Sales order header';
CREATE INDEX IX_ORDER_CUST_IDX ON ORDER(CUST_ID);
CREATE INDEX IX_ORDER_COUNTRY_IDX ON ORDER(COUNTRY_CODE);
