CREATE TABLE SALES_ORD (
    SALES_ORD_ID NUMBER NOT NULL,
    ORD_DT VARCHAR2(255) NOT NULL,
    CUST_ID NUMBER NOT NULL,
    ORD_STAT VARCHAR2(255) NOT NULL,
    SHIPPING_CTRY_CD VARCHAR2(255) NOT NULL,
    CONSTRAINT PK_SALES_ORD PRIMARY KEY (SALES_ORD_ID),
    CONSTRAINT FK_SALES_ORD_CUST FOREIGN KEY (CUST_ID) REFERENCES CUST(CUST_ID),
    CONSTRAINT FK_SALES_ORD_CTRY FOREIGN KEY (SHIPPING_CTRY_CD) REFERENCES CTRY(CTRY_CD),
    CONSTRAINT FK_SALES_ORD_SALES_ORD_LINE FOREIGN KEY (SALES_ORD_ID) REFERENCES SALES_ORD_LINE(SALES_ORD_ID)
);
COMMENT ON TABLE SALES_ORD IS 'Sales order header';
COMMENT ON COLUMN SALES_ORD.SALES_ORD_ID IS 'unique identifier for a sales order';
CREATE INDEX IDX_SALES_ORD_CUST ON SALES_ORD(CUST_ID);
CREATE INDEX IDX_SALES_ORD_CTRY ON SALES_ORD(SHIPPING_CTRY_CD);
CREATE INDEX IDX_SALES_ORD_SALES_ORD_LINE ON SALES_ORD(SALES_ORD_ID);
