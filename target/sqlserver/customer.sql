CREATE TABLE CUST (
    CUST_ID BIGINT NOT NULL,
    CUST_NAME VARCHAR(255) NOT NULL,
    EMAIL_ADDRESS VARCHAR(255),
    CTRY_CD VARCHAR(255) NOT NULL,
    CREATED_AT DATETIME2 NOT NULL,
    CONSTRAINT PK_CUST PRIMARY KEY (CUST_ID),
    CONSTRAINT FK_CUST_SALES_ORD FOREIGN KEY (CUST_ID) REFERENCES SALES_ORD(CUST_ID),
    CONSTRAINT FK_CUST_CTRY FOREIGN KEY (CTRY_CD) REFERENCES CTRY(CTRY_CD)
);
COMMENT ON TABLE CUST IS 'Customer master data';
COMMENT ON COLUMN CUST.CUST_ID IS 'unique identifier for a customer';
CREATE INDEX IDX_CUST_SALES_ORD ON CUST(CUST_ID);
CREATE INDEX IDX_CUST_CTRY ON CUST(CTRY_CD);
