CREATE TABLE PROD (
    PROD_ID NUMBER NOT NULL,
    SKU VARCHAR(255) NOT NULL,
    PROD_NAME VARCHAR(255) NOT NULL,
    PROD_STAT VARCHAR(255) NOT NULL,
    CONSTRAINT PK_PROD PRIMARY KEY (PROD_ID),
    CONSTRAINT FK_PROD_SALES_ORD_LINE FOREIGN KEY (PROD_ID) REFERENCES SALES_ORD_LINE(PROD_ID)
);
COMMENT ON TABLE PROD IS 'Product catalogue';
COMMENT ON COLUMN PROD.PROD_ID IS 'unique identifier for a product';
CREATE INDEX IDX_PROD_SALES_ORD_LINE ON PROD(PROD_ID);
